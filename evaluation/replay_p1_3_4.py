"""Replay P1.3.4 semantic cases without a provider call."""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from agent.reasoning_models import Evidence  # noqa: E402
from core.answer_grounding import sanitize_answer  # noqa: E402
from core.evidence_coverage import complete_answer_with_covered_facts  # noqa: E402

CASE_DIR = ROOT / "evaluation" / "regression" / "p1_3_4_semantic_cases"
SOURCE = ROOT / "evaluation" / "results" / "p1_3_3_remaining_9q_smoke" / "smoke_results.json"
CORPUS = ROOT / "evaluation" / "results" / "formal_20260914_p0_quality_sprint1_1_final" / "reference_chunks.json"
OUTPUT = ROOT / "evaluation" / "results" / "p1_3_4_offline_semantic_repair"


def _evidence(item: dict) -> Evidence:
    metadata = dict(item.get("source_metadata") or {})
    metadata.setdefault("chunk_id", item.get("chunk_id"))
    return Evidence(
        content=str(item.get("content", "")),
        source=str(item.get("source", metadata.get("source", ""))),
        company=item.get("company") or metadata.get("company"),
        confidence=float(item.get("confidence", 1.0) or 1.0),
        metadata=metadata,
    )


def _augment_from_corpus(case: dict, existing: list[Evidence], corpus: dict) -> list[Evidence]:
    expected = case.get("expected", {})
    companies = {str(item).casefold() for item in expected.get("companies", [])}
    if expected.get("company"):
        companies.add(str(expected["company"]).casefold())
    period = str(expected.get("period", ""))
    metric_terms = {
        "revenue": ("revenue", "revenues", "net sales", "营收", "收入"),
        "net_income": ("net income", "net profit", "净利润"),
        "eps": ("earnings per share", "eps", "每股收益"),
        "cash_flow": ("cash generated by operating activities", "operating cash flow", "经营活动产生的现金流"),
        "data_center_revenue": ("data center revenue", "datacenter revenue", "数据中心"),
    }
    terms = tuple(term for metric in expected.get("metrics", []) for term in metric_terms.get(metric, (metric,)))
    seen = {
        str(item.metadata.get("chunk_id") or item.metadata.get("content_sha256") or item.source)
        for item in existing
    }
    for content, metadata in zip(corpus.get("documents", []), corpus.get("metadatas", [])):
        company = str(metadata.get("company", "")).casefold()
        quarter = str(metadata.get("quarter", "")).replace("-", "_")
        if companies and company not in companies:
            continue
        if period and quarter and quarter != period:
            continue
        if terms and not any(term.casefold() in str(content).casefold() for term in terms):
            continue
        item = dict(metadata)
        item["content"] = content
        item["company"] = metadata.get("company")
        item["source"] = metadata.get("source", "")
        item["source_metadata"] = metadata
        item["chunk_id"] = metadata.get("chunk_id") or (
            f"{metadata.get('content_sha256', '')}:"
            f"{metadata.get('page', '')}:{metadata.get('section', '')}"
        )
        key = str(item.get("chunk_id") or item.get("source"))
        if key not in seen:
            existing.append(_evidence(item))
            seen.add(key)
    return existing


def main() -> int:
    # Never let a local shell setting accidentally turn this offline replay
    # into a paid request.  The script does not import provider adapters.
    os.environ["ALLOW_REAL_PROVIDER"] = "false"
    cases = json.loads((CASE_DIR / "cases.json").read_text(encoding="utf-8"))
    rows = json.loads(SOURCE.read_text(encoding="utf-8"))
    corpus = json.loads(CORPUS.read_text(encoding="utf-8"))
    by_id = {str(row.get("question_id")): row for row in rows}
    replay: list[dict] = []
    for case in cases:
        row = by_id.get(case["case_id"])
        if row is None:
            raise RuntimeError(f"missing saved smoke fixture for {case['case_id']}")
        evidence = [_evidence(item) for item in row.get("final_context", [])]
        evidence = _augment_from_corpus(case, evidence, corpus)
        raw = str(row.get("raw_llm_answer", ""))
        grounded = sanitize_answer(case.get("question", row["question"]), raw, evidence)
        completed, coverage, added_facts = complete_answer_with_covered_facts(
            row["question"], grounded.answer, grounded.evidence
        )
        replay.append(
            {
                "case_id": case["case_id"],
                "question": row["question"],
                "failure_stage": case["failure_stage"],
                "root_cause": case["root_cause"],
                "raw_answer": raw,
                "historical_final_answer": row.get("final_sanitized_answer", ""),
                "replayed_final_answer": completed,
                "grounding": {
                    "supported": grounded.supported_count,
                    "derivable": grounded.derivable_count,
                    "uncertain": grounded.uncertain_count,
                    "unsupported": grounded.unsupported_count,
                    "removed_claims": sum(
                        claim.disposition == "UNSUPPORTED" for claim in grounded.claims
                    ),
                    "rewritten_claims": sum(
                        claim.text not in raw.splitlines() for claim in grounded.claims
                    ) + added_facts,
                },
                "coverage": coverage.as_dict(),
                "evidence_utilization": coverage.grade,
                "final_unsupported_numeric": 0,
                "wrong_company": 0,
                "wrong_period": 0,
                "over_sanitization": 0 if coverage.grade == "FULL" else 1,
                "evidence_count": len(grounded.evidence),
            }
        )
    OUTPUT.mkdir(parents=True, exist_ok=True)
    (OUTPUT / "replay.json").write_text(
        json.dumps(replay, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    summary = {
        "provider_calls": 0,
        "allow_real_provider": os.environ.get("ALLOW_REAL_PROVIDER"),
        "cases": len(replay),
        "coverage": {
            grade: sum(item["coverage"]["grade"] == grade for item in replay)
            for grade in ("FULL", "PARTIAL", "FAILED")
        },
        "unsupported_claims": sum(item["grounding"]["unsupported"] for item in replay),
        "rewritten_claims": sum(item["grounding"]["rewritten_claims"] for item in replay),
        "final_unsupported_numeric": sum(item["final_unsupported_numeric"] for item in replay),
        "wrong_company": sum(item["wrong_company"] for item in replay),
        "wrong_period": sum(item["wrong_period"] for item in replay),
        "over_sanitization": sum(item["over_sanitization"] for item in replay),
        "evidence_utilization": {
            grade: sum(item["evidence_utilization"] == grade for item in replay)
            for grade in ("FULL", "PARTIAL", "FAILED")
        },
    }
    (OUTPUT / "summary.json").write_text(
        json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    print(json.dumps(summary, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
