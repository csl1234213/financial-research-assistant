def test_financial_summary_keeps_bounded_headline_probes_in_both_languages():
    english = retrieval_probe_queries(
        "Summarize NVIDIA's financial performance in Q1 FY2027.",
        QueryScope.SUMMARY,
    )
    chinese = retrieval_probe_queries(
        "总结英伟达 2027 财年第一季度的财务表现。",
        QueryScope.SUMMARY,
    )

    expected = {
        "NVIDIA total revenues Q1_FY2027",
        "NVIDIA net income Q1_FY2027",
        "NVIDIA gross profit Q1_FY2027",
        "NVIDIA gross margin Q1_FY2027",
        "NVIDIA operating margin Q1_FY2027",
        "NVIDIA cash generated by operating activities Q1_FY2027",
        "NVIDIA net cash provided by operating activities Q1_FY2027",
        "NVIDIA eps Q1_FY2027",
    }
    assert expected <= set(english)
    assert expected <= set(chinese)


