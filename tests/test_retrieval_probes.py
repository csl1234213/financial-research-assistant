def test_narrative_business_development_does_not_probe_unrequested_financial_tables():
    questions = (
        "Summarize Tesla's major business developments during Q2 2025.",
        "总结特斯拉 2025 年第二季度的主要业务发展。",
    )
    for question in questions:
        probes = retrieval_probe_queries(question, QueryScope.SUMMARY)
        assert all("financial summary" not in query for query in probes)
        assert all(not query.endswith(("revenue", "net income", "earnings per share")) for query in probes)
        assert all("segment revenue growth drivers" not in query for query in probes)


