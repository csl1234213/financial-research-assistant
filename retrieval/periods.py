"""Deterministic company-report period and metric hints.

The filename is not authoritative for a financial period: a report can contain
several comparative quarters (the Tesla Q4/FY2025 update is one example).
These helpers therefore recognise period labels in the extracted text and in
the user query, and return stable keys used only for retrieval constraints.
"""

from __future__ import annotations

import re

from core.financial_grounding import extract_normalized_numbers

_QUARTER = r"(?P<quarter>[1-4])"
_YEAR = r"(?P<year>20\d{2})"

_PERIOD_PATTERNS = (
    # Financial releases commonly abbreviate fiscal years in table headers
    # (``Q1 FY27``) or spell them out (``Q1 Fiscal 2027``). Keep the fiscal
    # marker so these are not confused with calendar-quarter labels.
    re.compile(
        rf"\bQ{_QUARTER}\s*[-/_]?\s*(?P<fiscal>FY|Fiscal)?\s*"
        r"(?P<year>20\d{2}|\d{2})\b",
        re.IGNORECASE,
    ),
    # Require the separator for reverse labels such as ``2025-Q2``.  Allowing
    # it to be absent made a forward sequence (``Q4-2024 Q1-2025``) overlap as
    # the phantom reverse label ``2024 Q1``.
    re.compile(rf"\b{_YEAR}\s*[-/]\s*Q{_QUARTER}\b", re.IGNORECASE),
    re.compile(
        rf"\b(?:first|1st|second|2nd|third|3rd|fourth|4th)\s+quarter"
        rf"\s+(?:of\s+)?(?:(?:fiscal(?:\s+year)?|fy)\s*)?{_YEAR}\b",
        re.IGNORECASE,
    ),
    re.compile(
        rf"\b(?:first|1st|second|2nd|third|3rd|fourth|4th)\s+"
        rf"(?:fiscal|fy)\s+quarter\s+(?:of\s+)?{_YEAR}\b",
        re.IGNORECASE,
    ),
)
_QUARTER_WORDS = {
    "first": 1,
    "1st": 1,
    "second": 2,
    "2nd": 2,
    "third": 3,
    "3rd": 3,
    "fourth": 4,
    "4th": 4,
}
_CJK_PERIOD = re.compile(r"(?P<year>20\d{2})\s*(?:年\s*)?(?:财年\s*)?(?:第)?(?P<quarter>[一二三四])季度")
_EXPLICIT_FISCAL_YEAR = (
    re.compile(r"\bFY\s*[-_/]?\s*(?P<year>20\d{2}|\d{2})\b", re.IGNORECASE),
    re.compile(
        r"\b(?:full[- ]year|annual|year ended|twelve months ended)"
        r"[\w\s,./-]{0,48}(?P<year>20\d{2})\b",
        re.IGNORECASE,
    ),
    re.compile(r"\b(?:fiscal\s+(?:year\s+)?)20(?P<short_year>\d{2})\b", re.IGNORECASE),
    # Some extracted Chinese annual-report titles contain the duplicated
    # marker ``2025 年年度报告``. This remains an explicit fiscal-year label.
    re.compile(r"(?P<year>20\d{2})\s*年\s*年度"),
    re.compile(r"(?P<year>20\d{2})\s*(?:财年|年度|全年)"),
)
_DURATION_TABLE = re.compile(
    r"\b(?:three|six|nine|twelve)\s+months?\s+(?:ended|ending)\b|"
    r"\b(?:quarter|quarterly)\s+ended\b|季度截至|季度结束",
    re.IGNORECASE,
)


def _normalize_quarter_marker(value: str) -> str:
    """Normalize fiscal-year marker spelling without changing quarter/year."""

    return value.upper().replace("-", "_").replace("_FY", "_")

